export function loadDatabase(): DatabaseSchema {
  try {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }
    if (!fs.existsSync(DB_FILE)) {
      fs.writeFileSync(DB_FILE, JSON.stringify(initialData, null, 2), 'utf-8');
      return structuredClone(initialData);
    }
    const raw = fs.readFileSync(DB_FILE, 'utf-8');
    const parsed = JSON.parse(raw) as DatabaseSchema;

    let mutated = false;
    if (!parsed.website_settings.homepage_stats) {
      parsed.website_settings.homepage_stats = initialData.website_settings.homepage_stats;
      mutated = true;
    }
    if (!parsed.website_settings.footer_description_ar) {
      parsed.website_settings.footer_description_ar =
        initialData.website_settings.footer_description_ar;
      mutated = true;
    }
    if (!parsed.website_settings.footer_copyright_ar) {
      parsed.website_settings.footer_copyright_ar =
        initialData.website_settings.footer_copyright_ar;
      mutated = true;
    }
    if (!parsed.website_settings.social_links.instagram) {
      parsed.website_settings.social_links.instagram =
        initialData.website_settings.social_links.instagram;
      mutated = true;
    }
    const sub1 = parsed.submissions.find((s) => s.id === 1);
    if (sub1 && sub1.payload && sub1.payload.category_name_ar) {
      sub1.payload = initialData.submissions[0].payload;
      mutated = true;
    }
    if (mutated) {
      saveDatabase(parsed);
    }
    return parsed;
  } catch (err) {
    console.error('Database load error, using in-memory initial data:', err);
    return structuredClone(initialData);
  }
}

export function saveDatabase(db: DatabaseSchema): void {
  try {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }
    fs.writeFileSync(DB_FILE, JSON.stringify(db, null, 2), 'utf-8');
  } catch (err) {
    console.error('Failed to persist database:', err);
  }
}

export function createSlug(text: string): string {
  const clean = text
    .toLowerCase()
    .trim()
    .replace(/[^\u0600-\u06FFa-z0-9\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-');
  return clean || `item-${Date.now()}`;
}
